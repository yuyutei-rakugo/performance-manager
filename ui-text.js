const htmlEntities = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, char => htmlEntities[char]);
}

export function errorMessage(error, fallback) {
  return error?.message || fallback;
}
